# Independent display checks: conservation of probability mass, exact readout and no resimulation.
e <- new.env(parent=globalenv()); invisible(sys.source("app_core.R",envir=e));attach(e)
checks <- list()
check <- function(ok,label){if(!isTRUE(ok))stop(label);checks[[length(checks)+1]]<<-list(label=label,status="passed");cat("PASS:",label,"\n")}
grid<-c(30,60,90)
mat<-rbind(c(4,4,5),c(4,5,6),c(4,6,7),c(4,4,4))
cur<-curve_from_counts(mat,grid,"指数","exponential",6)
r<-list(config=list(cut=30,horizon=60,display_unit="months",origin="2025-01-01",task="count",input_mode="parameters",target=6),curves=cur,counts=list(exponential=mat),known_events=4,milestones=list(exponential=c(Inf,80,60,Inf)))
d<-core_count_mass(r,2)
check(sum(d$frequency)==4&&sum(d$probability)==1&&identical(d$count,c(4,5,6)),"count distribution preserves all integer observations and actual successful denominator")
n<-core_count_mass(r,2,new=TRUE)
check(identical(n$count,c(0,1,2))&&identical(n$probability,d$probability),"new counts shift support by fixed D0 without changing probabilities")
read<-core_forecast_readout(r,2)
check(read$累计均值==4.75&&read$新增均值==.75&&read$成功模拟次数==4&&abs(read[[3]]-30/30.4375)<1e-12,"selected time readout uses exact original grid and saved units")
check(core_result_time_index(r,30/30.4375)==2,"elapsed time slider maps saved months to the original study-day grid")
check(core_result_index(r,999)==3&&core_result_index(r,-5)==1,"stale slider values clamp to new grid")
tm<-core_target_mass(r,bins=2)
check(sum(tm$frequency)==4&&sum(tm$probability)==1&&tail(tm$frequency,1)==2&&tm$frequency[2]==1&&tm$frequency[3]==1,"target bins include right endpoints and infinite unreached mass")
r$milestones$exponential<-rep(Inf,4)
check(tail(core_target_mass(r)$probability,1)==1,"all unreached trials remain visible rather than disappearing")
r$milestones$exponential<-c(20,30,90,Inf)
check(core_target_mass(r,bins=2)$frequency[1]==2&&core_target_mass(r,bins=2)$frequency[3]==1,"already reached and exact window-end hits are classified without fabricating a historical date")
set.seed(923);before<-.Random.seed
p<-plotly::plotly_build(core_forecast_plot(r,2,paths=TRUE))
check(identical(before,.Random.seed),"trajectory previews do not alter RNG or rerun simulation")
check(any(vapply(p$x$data,function(t)!is.null(t$customdata)&&length(t$customdata)==3,logical(1))),"forecast plot retains grid identifiers for linked click readout")
check(all(vapply(p$x$data,function(t)is.null(t$y)||all(is.finite(t$y)),logical(1))),"count plot handles finite paths and saved calendar axis")
d<-data.frame(SIMID=c(1,1,2,2),CUTID=c(1,2,1,2),scope="group",group=c("A","A","B","B"),events=1:4)
check(nrow(core_sim_filter(d,1,NULL,"A"))==2&&core_sim_filter(d,NULL,2,"B")$events==4,"simulation display filters trial, cut and group independently")
check(identical(r$counts$exponential,mat),"display transformations leave underlying simulations unchanged")
jsonlite::write_json(list(status="passed",passed=length(checks),checks=checks,scope="display transformations; underlying inference unchanged"),"validation/core_results_check.json",pretty=TRUE,auto_unbox=TRUE)
